// Merges tools/en/part*.json into src/lib/meeqo/en.ts. Run from meeqo-app: node tools/i18n-merge.mjs
import fs from "node:fs";
const merged = {};
for (const file of fs.readdirSync("tools/en").filter((name) => /^part\d+\.json$/.test(name)).sort()) {
  Object.assign(merged, JSON.parse(fs.readFileSync(`tools/en/${file}`, "utf8")));
}
const keys = Object.keys(merged).sort((a, b) => a.localeCompare(b, "de"));
const body = keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(merged[key])},`).join("\n");
fs.writeFileSync("src/lib/meeqo/en.ts", `/** English texts. The key is the German source text exactly as it appears in the code; {0}, {1} are filled values. Generated by tools/i18n-merge.mjs from tools/en/*.json. */\nexport const EN: Record<string, string> = {\n${body}\n};\n`);
console.log(keys.length, "texts");
